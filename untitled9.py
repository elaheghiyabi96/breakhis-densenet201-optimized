# ============================================
# DENSENET201 + TTA WITH RESUME CAPABILITY
# ============================================

import os
import numpy as np
import pandas as pd
import tensorflow as tf
from sklearn.model_selection import train_test_split
from sklearn.utils.class_weight import compute_class_weight
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score
from tensorflow.keras.applications import DenseNet201
from tensorflow.keras.layers import GlobalAveragePooling2D, Dense, Dropout, BatchNormalization
from tensorflow.keras.models import Sequential, load_model
from tensorflow.keras.optimizers import Adam
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau, ModelCheckpoint
from tensorflow.keras.preprocessing.image import ImageDataGenerator
import shutil

# =========================
# 1️⃣ Mount Drive
# =========================
from google.colab import drive
drive.mount('/content/drive')

# =========================
# 2️⃣ Extract Dataset
# =========================
import zipfile

ZIP_PATH = "/content/drive/MyDrive/dataset_cancer_v1.zip"
EXTRACT_PATH = "/content"

if not os.path.exists("/content/dataset_cancer_v1"):
    with zipfile.ZipFile(ZIP_PATH, 'r') as zip_ref:
        zip_ref.extractall(EXTRACT_PATH)
    print("✅ Extraction completed.")
else:
    print("✅ Dataset already extracted.")

BASE_DIR = "/content/dataset_cancer_v1/classificacao_binaria"
print(f"📁 BASE_DIR = {BASE_DIR}")

# =========================
# 3️⃣ Configurations
# =========================
IMG_SIZE = 224
BATCH_SIZE = 32
EPOCHS_PHASE1 = 30
EPOCHS_PHASE2 = 25
EPOCHS_PHASE3 = 15

label_map = {"benign": 0, "malignant": 1}
magnifications = ["40X", "100X", "200X", "400X"]

# =========================
# 4️⃣ Collect Image Paths
# =========================
filepaths = []
labels = []

for mag in magnifications:
    for cls in label_map.keys():
        folder = os.path.join(BASE_DIR, mag, cls)
        if not os.path.exists(folder):
            continue
        for img_name in os.listdir(folder):
            if img_name.lower().endswith(('.png', '.jpg', '.jpeg')):
                filepaths.append(os.path.join(folder, img_name))
                labels.append(label_map[cls])

filepaths = np.array(filepaths)
labels = np.array(labels)

print(f"📊 Total samples: {len(filepaths)}")

# =========================
# 5️⃣ Train / Val / Test Split
# =========================
X_temp, X_test, y_temp, y_test = train_test_split(
    filepaths, labels, test_size=0.15, stratify=labels, random_state=42
)

X_train, X_val, y_train, y_val = train_test_split(
    X_temp, y_temp, test_size=0.176, stratify=y_temp, random_state=42
)

train_df = pd.DataFrame({"filename": X_train, "class": y_train})
val_df = pd.DataFrame({"filename": X_val, "class": y_val})
test_df = pd.DataFrame({"filename": X_test, "class": y_test})

print(f"📊 Train: {len(train_df)}, Val: {len(val_df)}, Test: {len(test_df)}")

# =========================
# 6️⃣ Class Weights
# =========================
class_weights = compute_class_weight(
    class_weight='balanced',
    classes=np.unique(y_train),
    y=y_train
)
class_weight_dict = dict(enumerate(class_weights))
print(f"📊 Class Weights: {class_weight_dict}")

# =========================
# 7️⃣ Data Augmentation
# =========================
train_datagen = ImageDataGenerator(
    rescale=1./255,
    rotation_range=45,
    width_shift_range=0.25,
    height_shift_range=0.25,
    shear_range=0.2,
    zoom_range=0.25,
    horizontal_flip=True,
    vertical_flip=True,
    brightness_range=[0.6, 1.4],
    channel_shift_range=15,
    fill_mode='reflect'
)

val_datagen = ImageDataGenerator(rescale=1./255)

train_generator = train_datagen.flow_from_dataframe(
    train_df, x_col="filename", y_col="class",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=True
)

val_generator = val_datagen.flow_from_dataframe(
    val_df, x_col="filename", y_col="class",
    target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
    class_mode="raw", shuffle=False
)

steps_per_epoch = len(train_df) // BATCH_SIZE
validation_steps = len(val_df) // BATCH_SIZE

# =========================
# 8️⃣ Check if Model Already Exists
# =========================
MODEL_PATH_DRIVE = "/content/drive/MyDrive/densenet201_optimized_final.keras"
MODEL_PATH_COLAB = "/content/densenet201_optimized_final.keras"

if os.path.exists(MODEL_PATH_DRIVE):
    print(f"\n✅ Model found in Google Drive: {MODEL_PATH_DRIVE}")
    print("🔄 Loading model from Drive...")
    model = load_model(MODEL_PATH_DRIVE)
    print("✅ Model loaded! Skipping training.")
    TRAIN_NEEDED = False
elif os.path.exists(MODEL_PATH_COLAB):
    print(f"\n✅ Model found in Colab: {MODEL_PATH_COLAB}")
    print("🔄 Loading model...")
    model = load_model(MODEL_PATH_COLAB)
    print("✅ Model loaded! Skipping training.")
    TRAIN_NEEDED = False
else:
    print("\n❌ Model not found. Training required.")
    TRAIN_NEEDED = True

# =========================
# 9️⃣ Train if Needed
# =========================
if TRAIN_NEEDED:
    print("\n🧠 Building DenseNet201 model...")

    base_model = DenseNet201(
        weights='imagenet',
        include_top=False,
        input_shape=(IMG_SIZE, IMG_SIZE, 3)
    )
    base_model.trainable = False

    model = Sequential([
        base_model,
        GlobalAveragePooling2D(),
        BatchNormalization(),
        Dense(512, activation='relu'),
        Dropout(0.5),
        Dense(256, activation='relu'),
        Dropout(0.3),
        Dense(1, activation='sigmoid')
    ])

    model.summary()

    # Phase 1: Frozen
    print("\n🚀 PHASE 1: Training DenseNet201 (Frozen)")
    model.compile(optimizer=Adam(1e-3), loss='binary_crossentropy', metrics=['accuracy'])

    callbacks = [
        EarlyStopping(patience=8, restore_best_weights=True, verbose=1),
        ReduceLROnPlateau(factor=0.3, patience=4, min_lr=1e-7, verbose=1),
        ModelCheckpoint('densenet201_best.keras', save_best_only=True, verbose=1)
    ]

    history1 = model.fit(
        train_generator, steps_per_epoch=steps_per_epoch, epochs=EPOCHS_PHASE1,
        validation_data=val_generator, validation_steps=validation_steps,
        class_weight=class_weight_dict, callbacks=callbacks, verbose=1
    )

    # Phase 2: Fine-Tuning
    print("\n🔧 PHASE 2: Fine-Tuning")
    base_model.trainable = True
    for layer in base_model.layers[:-30]:
        layer.trainable = False

    model.compile(optimizer=Adam(5e-5), loss='binary_crossentropy', metrics=['accuracy'])

    history2 = model.fit(
        train_generator, steps_per_epoch=steps_per_epoch, epochs=EPOCHS_PHASE2,
        validation_data=val_generator, validation_steps=validation_steps,
        class_weight=class_weight_dict, callbacks=callbacks, verbose=1
    )

    # Phase 3: Final FT
    print("\n🔧 PHASE 3: Final Fine-Tuning")
    model.compile(optimizer=Adam(1e-5), loss='binary_crossentropy', metrics=['accuracy'])

    history3 = model.fit(
        train_generator, steps_per_epoch=steps_per_epoch, epochs=EPOCHS_PHASE3,
        validation_data=val_generator, validation_steps=validation_steps,
        class_weight=class_weight_dict, callbacks=callbacks, verbose=1
    )

    # Save Model
    print("\n💾 Saving model...")
    model.save(MODEL_PATH_COLAB)
    shutil.copy(MODEL_PATH_COLAB, MODEL_PATH_DRIVE)
    print("✅ Model saved in Colab and Google Drive")

    # Original Test Accuracy
    test_datagen = ImageDataGenerator(rescale=1./255)
    test_generator = test_datagen.flow_from_dataframe(
        test_df, x_col="filename", y_col="class",
        target_size=(IMG_SIZE, IMG_SIZE), batch_size=BATCH_SIZE,
        class_mode="raw", shuffle=False
    )

    test_loss, original_acc = model.evaluate(test_generator, verbose=0)
    print(f"\n✅ Original Test Accuracy: {original_acc:.4f} ({original_acc*100:.2f}%)")

# =========================
# 🔟 TTA Evaluation
# =========================
print("\n🎯 Running TTA...")

def load_image(img_path):
    img = tf.keras.utils.load_img(img_path, target_size=(IMG_SIZE, IMG_SIZE))
    return tf.keras.utils.img_to_array(img) / 255.0

test_images = np.array([load_image(p) for p in X_test])
print(f"✅ Loaded {len(test_images)} test images")

def predict_with_tta(img, n_aug=5):
    preds = [model.predict(np.expand_dims(img, axis=0), verbose=0)[0][0]]
    for _ in range(n_aug):
        aug = img.copy()
        if np.random.random() > 0.5:
            aug = np.fliplr(aug)
        if np.random.random() > 0.5:
            aug = aug * np.random.uniform(0.7, 1.3)
        if np.random.random() > 0.5:
            aug = np.flipud(aug)
        preds.append(model.predict(np.expand_dims(aug, axis=0), verbose=0)[0][0])
    return np.mean(preds)

print("\n⏳ Processing TTA predictions...")
tta_preds = []
for i, img in enumerate(test_images):
    pred = predict_with_tta(img)
    tta_preds.append(1 if pred > 0.5 else 0)
    if (i + 1) % 100 == 0:
        print(f"✅ Processed {i+1}/{len(test_images)}")

tta_accuracy = accuracy_score(y_test, tta_preds)

# =========================
# 1️⃣1️⃣ Final Results
# =========================
print("\n" + "="*60)
print("📊 FINAL RESULTS")
print("="*60)
print(f"\n📊 Original Accuracy:  {original_acc*100:.2f}%")
print(f"📊 TTA Accuracy:      {tta_accuracy*100:.2f}%")
print(f"📈 Improvement:       {(tta_accuracy - original_acc)*100:.2f}%")

print("\n📋 TTA Classification Report:")
print(classification_report(y_test, tta_preds, target_names=["Benign", "Malignant"]))

print("\n📊 TTA Confusion Matrix:")
print(confusion_matrix(y_test, tta_preds))

print("\n🎉 TTA Complete!")